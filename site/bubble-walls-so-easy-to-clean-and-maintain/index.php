When you’ve added a beautiful, new water feature such as a <a href="/bubble-walls/">bubble wall</a> to your indoor environment, it’s only natural to want to take proper care of it. This is especially true when you create a custom-built design with Midwest Tropical. Built to your specifications and designed with your location in mind, your water feature can be a real standout.

Unlike aquariums or indoor water fountains that can require a lot of upkeep, bubble walls are pretty simple to protect. Here’s what you need to know from Midwest Tropical.
<h2>They’re Virtually Maintenance-Free</h2>
Midwest Tropical has invented the first line of almost completely maintenance-free sealed and enclosed bubble walls. They are sealed and enclosed, design to prevent evaporation. These walls should be filled using only distilled water, and you won’t have to think about the water level again. By comparison, other bubble walls require you to top off the water regularly. You may also want to check the airline connections regularly to catch leaks or loosening tubes before they get too serious.
<h2>Cleaning Frequency</h2>
If you are using distilled water, your bubble wall will only need to be cleaned about every three months.
<h2>Equipment to Gather</h2>
To properly clean your Midwest Tropical bubble wall, you’ll only need a few simple cleaning items, such as:
<ul style="list-style-type: disc;">
	<li>A soft, damp towel</li>
	<li>Acrylic cleaners such as NOVUS or Plexus®</li>
	<li>A toothbrush for cleaning tricky areas</li>
</ul>
Never use any chemicals or cleaning agents, and avoid abrasive cleaners or glass cleaners, which can damage the wall. Likewise, do not use metal brushes, picks, needles or any other tools that could harm your water feature.
<h2>The Cleaning Process</h2>
To clean your bubble panel, wipe it with a soft, damp towel. A toothbrush works great for getting those hard-to-clean areas.
