<p class="wp-block-paragraph">Since 1977, Midwest Tropical has designed and installed custom water features in all 50 states and internationally. We offer a wide variety of water features, including rain curtains, bubble walls, water walls, bubble tubes, reflection pools, fountains, and indoor water fountains. We can also help you custom design a water feature that perfectly meets your needs and budget.</p>



