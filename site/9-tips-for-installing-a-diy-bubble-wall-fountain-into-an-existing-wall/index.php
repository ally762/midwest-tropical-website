<p>Within our extensive collection of water features, some of our bubble wall fountain units require a DIY job to install it efficiently into an existing wall in your home or business.</p>
<p>&nbsp;</p>
<p>Now you can create your <a href="/bubble-walls/">bubble wall</a> like a pro, but first, you would need an in-depth assessment of what you need to do to install properly those panels for a better ambiance.</p>
<ol>
<li>The foremost thing that any professional will teach involves building a double-sided frame around the panel to encase it in wall-mounted installations.</li>
<li>Secondly, make the frame components easily removable using screws or similar fasteners.</li>
<li>While you may forget in the pressure of doing crucial craftsmanship for the very first time, it&#x2122;s our prime duty to remind you to make the bubble panel properly supported from the bottom of the unit. Moreover, all of the weight should rest on the bottom edge.</li>
<li>Work discretely on the vertical support on both sides of the panel to keep the unit in an upright position.</li>
<li>Use an adhesive foam strip to cushion the unit on harder surfaces.</li>
<li>The next step enforces you to make sure the unit is mounted in the appropriate level position so that there is no likelihood of water spillage- enabling the energetic bubble output.</li>
<li>Especially the top of the unit must be accessible so that you can conveniently pour water into it. This also helps make removal and re-installation of the entire panel smooth when you want to give your <a href="/bubble-walls/">led bubble wall</a> a thorough cleanup or want to refresh the tank water.</li>
</ol>
<p><strong>Things You Shouldn&#x2122;t DIY</strong></p>
<p>1. Avoid drilling or screwing into the bubble wall panel.</p>
<p>&nbsp;</p>
<p>2. It is strictly prohibited to use glues and/or solvents to mount the unit.</p>
<p>&nbsp;</p>
<p>3. Other components that contribute correspondingly to a robust bubble wall lightening action includes air pump and LED power supply. They should not be mounted under the unit, but rather to either side of the panel in a remote location with access to power.</p>
<p>These are all the important tips for installing DIY aquarium bubble walls fountain. We hope these step-by-step instructions become an ultimate checklist when you look up ways to build a steady underwater environment. Since many of you haven&#x2122;t done anything like this in history, it might be a challenging experience for you, but here with our brief, the entire process becomes an enterprising experience.</p>
<p>&nbsp;</p>
<p>For more helpful tips on constructing a flawless bubble wall, call Midwest-Tropical at 847-679-6666.</p>
